#include <iostream> 
using namespace std;
int x = 1;
int y = 1;
int main() {
    cout << "1) " << x << " + " << y << " = " << x + y << endl;
    cout << "2) " << x << " - " << y << " = " << x - y << endl;
    cout << "3) " << x << " * " << y << " = " << x * y << endl;
    cout << "4) " << x << " / " << y << " = " << x / y << endl;
}                 
